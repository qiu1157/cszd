import { describe, expect, it } from 'vitest'

import source from './StationListView.vue?raw'

describe('StationListView source', () => {
  it('应渲染基础列表结构，并提供新增入口', () => {
    expect(source).toContain('充电站管理')
    expect(source).toContain('新增充电站')
    expect(source).toContain('编辑')
    expect(source).toContain('goToEdit')
    expect(source).toContain('goToDetail')
    expect(source).toContain('请输入充电站名称')
    expect(source).toContain('请选择平台')
    expect(source).toContain('请选择状态')
    expect(source).toContain('platformOptions')
    expect(source).toContain('statusOptions')
    expect(source).toContain('searchForm.platformItemId')
    expect(source).toContain('searchForm.stationStatusItemId')
    expect(source).toContain('查询')
    expect(source).toContain('@keyup.enter')
    expect(source).toContain('@click="goToCreate"')
    expect(source).toContain('充电站编号')
    expect(source).toContain('所在平台')
    expect(source).toContain('当前状态')
    expect(source).toContain('查看详情')
    expect(source).not.toContain(':disabled="true">查看详情')
    expect(source).not.toContain('按名称搜索')
    expect(source).not.toContain('平台筛选')
    expect(source).not.toContain('状态筛选')
  })

  it('应提供股东关系导入模板下载与批量导入入口，且导入仅系统管理员可见', () => {
    expect(source).toContain('下载股东投资模板')
    expect(source).toContain('handleDownloadTemplate')
    expect(source).toContain('downloadShareholdingImportTemplate')
    expect(source).toContain('导入关系')
    expect(source).toContain('v-if="canImport"')
    expect(source).toContain('openImportDialog')
    expect(source).toContain('canImport')
    expect(source).toContain('USER_ROLES.SYSTEM_ADMIN')
    expect(source).toContain('useAuthStore')
    expect(source).toContain('shareholding-import-dialog')
    expect(source).toContain('importDialogVisible')
    expect(source).toContain('el-upload')
    expect(source).toContain('accept=".xlsx"')
    expect(source).toContain('importShareholdings')
    expect(source).toContain('submitImport')
    expect(source).toContain('handleImportFileChange')
    expect(source).toContain('importErrors')
    expect(source).toContain('import-result__title')
    expect(source).toContain('导入仅新增')
  })
})
